"""Writes the snapshot, `latest.json` and the history index."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .slots import parse

INDEX_VERSION = 1


def dump(data: Any) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def snapshot_path(root: Path, checked_at: str) -> Path:
    """`history/YYYY/MM/DD/HHmm.json` for a snapshot taken at `checked_at` (UTC).

    Never an existing file: a second run in the same minute gets `HHmmss`, then `-2`, `-3`...
    """
    when = parse(checked_at)
    folder = root / "history" / when.strftime("%Y") / when.strftime("%m") / when.strftime("%d")
    candidate = folder / f"{when.strftime('%H%M')}.json"
    if not candidate.exists():
        return candidate
    candidate = folder / f"{when.strftime('%H%M%S')}.json"
    counter = 2
    while candidate.exists():
        candidate = folder / f"{when.strftime('%H%M%S')}-{counter}.json"
        counter += 1
    return candidate


def read_latest(root: Path) -> dict[str, Any] | None:
    path = root / "latest.json"
    if not path.exists():
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    return data if isinstance(data, dict) else None


def write_snapshot(root: Path, snapshot: dict[str, Any]) -> Path:
    path = snapshot_path(root, snapshot["checked_at"])
    path.parent.mkdir(parents=True, exist_ok=True)
    text = dump(snapshot)
    path.write_text(text, encoding="utf-8", newline="\n")
    (root / "latest.json").write_text(text, encoding="utf-8", newline="\n")
    return path


# ---------------------------------------------------------------------------- index


def _empty_index() -> dict[str, Any]:
    return {"index_version": INDEX_VERSION, "updated_at": None, "snapshots_total": 0, "days": {}, "changes": [], "missed": []}


def read_index(root: Path) -> dict[str, Any]:
    path = root / "history" / "index.json"
    if not path.exists():
        return _empty_index()
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(data, dict) and data.get("index_version") == INDEX_VERSION:
            return data
    except (OSError, json.JSONDecodeError):
        pass
    return _empty_index()


def update_index(index: dict[str, Any], snapshot: dict[str, Any], rel_path: str) -> dict[str, Any]:
    """Folds one snapshot into the index (pure; returns the same dict, updated)."""
    day = snapshot["checked_at"][:10]
    run = snapshot["run"]
    entry = index["days"].setdefault(day, {"snapshots": 0, "late": 0, "missed": 0, "changed": 0, "failed": 0})
    entry["snapshots"] += 1
    entry["late"] += 1 if run["late"] else 0
    entry["missed"] += run["missed_count"]
    changed = bool(snapshot["changes"]["any"])
    entry["changed"] += 1 if changed else 0
    entry["failed"] += 1 if run.get("validation_errors") else 0

    index["snapshots_total"] += 1
    index["updated_at"] = snapshot["checked_at"]
    if changed:
        index["changes"].append(
            {
                "checked_at": snapshot["checked_at"],
                "path": rel_path,
                "summary": snapshot["changes"]["summary"],
            }
        )
    for slot in run["missed_slots"]:
        index["missed"].append({"slot": slot, "noticed_at": snapshot["checked_at"], "path": rel_path})
    return index


def render_index_md(index: dict[str, Any]) -> str:
    lines = [
        "# History index",
        "",
        "Generated by the collector on every run; the machine-readable copy is [`index.json`](index.json).",
        "Times are UTC. A day has 48 slots (every 30 minutes); fewer snapshots than 48 means GitHub",
        "skipped or delayed runs, which is recorded below rather than hidden.",
        "",
        f"Snapshots recorded: **{index['snapshots_total']}**. Last: `{index['updated_at']}`.",
        "",
        "## Snapshots per day",
        "",
        "| Day | Snapshots | Changed | Late | Missed slots | Failed |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for day in sorted(index["days"], reverse=True):
        d = index["days"][day]
        lines.append(f"| {day} | {d['snapshots']} | {d['changed']} | {d['late']} | {d['missed']} | {d['failed']} |")

    lines += ["", "## Runs where something changed", ""]
    if index["changes"]:
        for change in reversed(index["changes"]):
            lines.append(f"- `{change['checked_at']}` [{change['summary']}]({change['path'].removeprefix('history/')})")
    else:
        lines.append("Nothing has changed yet.")

    lines += ["", "## Missed slots", ""]
    if index["missed"]:
        for miss in reversed(index["missed"]):
            lines.append(f"- `{miss['slot']}` (noticed at `{miss['noticed_at']}`)")
    else:
        lines.append("None recorded.")
    return "\n".join(lines) + "\n"


def write_index(root: Path, snapshot: dict[str, Any], snapshot_file: Path) -> dict[str, Any]:
    index = read_index(root)
    rel = snapshot_file.relative_to(root).as_posix()
    update_index(index, snapshot, rel)
    history = root / "history"
    history.mkdir(parents=True, exist_ok=True)
    (history / "index.json").write_text(dump(index), encoding="utf-8", newline="\n")
    (history / "INDEX.md").write_text(render_index_md(index), encoding="utf-8", newline="\n")
    return index
